"use strict";
const fs = require("node:fs"), path = require("node:path"), crypto = require("node:crypto"), assert = require("node:assert/strict");
const root = path.resolve(__dirname, "../web");
const paths = ["js/vendor/sax.js", ...["byte-source.js", "decimal.js", "engine.js", "executor.js", "expression.js", "json.js",
    "native-runtime.js", "runtime.html", "selectors.js", "snapshot.js", "sources.js", "template.js", "transform.js", "worker.js",
    "xlsx-reader.js", "xlsx-zip.js"].map(file => "tabular/" + file)].sort();
const engine = fs.readFileSync(path.join(root, "tabular/engine.js"), "utf8");
const manifest = { formatVersion: 1, workerProtocol: Number(engine.match(/protocol: (\d+)/)[1]),
    engineRevision: engine.match(/const revision = "([^"]+)"/)[1], entry: "tabular/runtime.html",
    files: paths.map(file => {
        assert.ok(fs.lstatSync(path.join(root, file)).isFile(), "Only regular shipped files: " + file);
        const bytes = fs.readFileSync(path.join(root, file));
        return { path: file, bytes: bytes.length, sha256: crypto.createHash("sha256").update(bytes).digest("hex") };
    }) };
const output = JSON.stringify(manifest, null, 2) + "\n", target = path.join(root, "tabular/runtime-lock.json");
const fingerprint = crypto.createHash("sha256").update(output).digest("hex");
const pinPath = path.resolve(root, "../src/RNAssistant.Application/TabularRuntimePin.cs");
const pin = "// Generated by tools/update-tabular-runtime-lock.js. Review runtime changes before updating.\n" +
    "namespace RNAssistant.Application\n{\n    internal static class TabularRuntimePin\n    {\n" +
    `        internal const string Sha256 = "${fingerprint}";\n    }\n}\n`;
assert.ok(process.argv.slice(2).every(arg => ["--write", "--check"].includes(arg)), "Use --write or --check");
if (process.argv.includes("--write")) { fs.writeFileSync(target, output); fs.writeFileSync(pinPath, pin); }
else {
    assert.equal(fs.readFileSync(target, "utf8"), output, "Runtime lock is stale; review changes and run with --write.");
    assert.equal(fs.readFileSync(pinPath, "utf8"), pin, "Native package pin differs from the shipped runtime lock.");
}
console.log(`Tabular runtime: ${paths.length} pinned files, ${manifest.files.reduce((sum, file) => sum + file.bytes, 0)} bytes`);
