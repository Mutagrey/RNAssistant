const engine = context.RNTabularEngine, templates = context.RNTabularTemplate;
const json = value => JSON.parse(JSON.stringify(value));
const example = () => JSON.parse(fs.readFileSync(path.join(root, "examples/matrix-extraction.json"), "utf8"));
const hooks = { isCancelled: () => false, yieldControl: async () => {}, onProgress: () => {} };
async function extract(value, extra = {}) {
    const records = [];
    const summary = await engine.extract(JSON.stringify(value), { ...hooks, onBatch: async batch => records.push(...json(batch.records)), ...extra });
    return { summary: json(summary), records };
}
async function rejects(change, code) {
    const value = example(); change(value);
    await assert.rejects(extract(value), error => error.code === code, code);
}
function larger() {
    const value = example(); value.template.source.bounds = "A1:AG40"; value.template.source.rows[0].select = "A12:A31";
    for (const range of value.snapshot.ranges) if (/12:.*13$/.test(range.address)) {
        range.address = range.address.replace(/13$/, "31");
        range.cells = Array.from({ length: 20 }, (_, index) => {
            const row = structuredClone(range.cells[0]);
            if (range.address.startsWith("A12:")) row[0].value = "code-" + index;
            return row;
        });
    }
    value.dictionaries.parameters = Array.from({ length: 20 }, (_, index) => ({ ...value.dictionaries.parameters[0], id: "parameter-" + index }));
    value.dictionaries.parameterMappings = Array.from({ length: 20 }, (_, index) => ({ scope: "production-form", source: "code-" + index, targetId: "parameter-" + index }));
    return value;
}

